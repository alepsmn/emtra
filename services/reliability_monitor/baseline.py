"""Detector baseline: mu0, sigma0 of the indicator per (line, segment, band group).

`python -m services.reliability_monitor.baseline` runs the 20 clean baseline days (INTERFACES
section 10) in batch and writes config/baselines/c19.yaml, which is committed.
"""

from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict

from emtra_common.config import CONFIG_DIR, load_model

BASELINE_PATH = CONFIG_DIR / "baselines" / "c19.yaml"


class BaselineCell(BaseModel):
    model_config = ConfigDict(extra="forbid")
    line_id: str
    segment_id: int
    band_group: str
    indicator: Literal["cvh", "otp"]
    mu0: float       # mean of x = c_vh, or 1 - OTP
    sigma0: float    # sample standard deviation of x
    n: int


class Baseline(BaseModel):
    model_config = ConfigDict(extra="forbid")
    cells: list[BaselineCell]

    def cell(self, line_id: str, segment_id: int, band_group: str) -> BaselineCell | None:
        for c in self.cells:
            if (c.line_id, c.segment_id, c.band_group) == (line_id, segment_id, band_group):
                return c
        return None


def load_baseline(path: Path | str | None = None) -> Baseline:
    return load_model(path or BASELINE_PATH, Baseline)


def indicator_x(indicator: str, value: float) -> float:
    """The monitored variable: c_vh, or 1 - OTP (both grow when reliability worsens)."""
    return value if indicator == "cvh" else 1.0 - value


def collect_status(seeds: list[int], root: Path):  # noqa: ANN201
    """Band statuses (DataFrame) of clean days: sim -> ingestor -> indicators, no detectors."""
    import pandas as pd

    from services.ingestor.batch import run_batch as ingest_batch
    from services.reliability_monitor.batch import load_events, replay
    from services.reliability_monitor.core.monitor import Monitor
    from sim.run import run_sim

    rows = []
    for seed in seeds:
        d = run_sim(seed, root / str(seed))
        ingest_batch(d)
        arrivals, marks = load_events(d)
        out = replay(Monitor(pd.read_parquet(d / "timetable.parquet")), arrivals, marks)
        rows += [{"seed": seed, **o.model_dump()} for o in out if hasattr(o, "indicator")]
    return pd.DataFrame(rows)


def build(status) -> Baseline:  # noqa: ANN001
    from emtra_common.bands import band_group

    s = status[status.value.notna()].copy()
    s["group"] = [band_group(t.to_pydatetime()) for t in s.band_start]
    s["x"] = [indicator_x(i, v) for i, v in zip(s.indicator, s.value, strict=True)]
    cells = []
    for (line, seg, group, ind), g in s.groupby(["line_id", "segment_id", "group", "indicator"]):
        cells.append(BaselineCell(line_id=line, segment_id=int(seg), band_group=group,
                                  indicator=ind, mu0=float(g.x.mean()),
                                  sigma0=float(g.x.std(ddof=1)), n=len(g)))
    return Baseline(cells=cells)


def main() -> None:
    import tempfile

    from emtra_common.config import load_data_split

    split = load_data_split().baseline
    with tempfile.TemporaryDirectory() as tmp:
        base = build(collect_status(list(range(split.first, split.last + 1)), Path(tmp)))
    BASELINE_PATH.parent.mkdir(parents=True, exist_ok=True)
    header = ("# Detector baseline: mu0, sigma0 of c_vh or 1 - OTP per line, segment, band group.\n"
              "# Generated by `python -m services.reliability_monitor.baseline` from seeds "
              f"{split.first}-{split.last}; committed, the demo does not recompute it.\n")
    BASELINE_PATH.write_text(header + yaml.safe_dump(base.model_dump(), sort_keys=False))
    print(f"wrote {BASELINE_PATH} ({len(base.cells)} cells)")


if __name__ == "__main__":
    main()
